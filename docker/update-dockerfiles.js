const fs = require('fs');
const dir = 'D:/Git/docker';
const services = ['bil-gateway','bil-auth','bil-user','bil-video','bil-interaction','bil-comment','bil-admin'];
const ports = {'bil-gateway':8080,'bil-auth':7072,'bil-user':7076,'bil-video':7073,'bil-interaction':7074,'bil-comment':7075,'bil-admin':7070};
const mavenOpts = 'ENV MAVEN_OPTS="-Xmx512m"';
services.forEach(name => {
  const port = ports[name];
  const lines = [];
  lines.push('FROM maven:3.9-eclipse-temurin-21 AS builder');
  lines.push('WORKDIR /build');
  lines.push(mavenOpts);
  lines.push('');
  lines.push('# maven aliyun mirror');
  lines.push('COPY docker/maven/settings.xml /root/.m2/settings.xml');
  lines.push('COPY pom.xml .');
  lines.push('COPY bil-common ./bil-common');
  lines.push('COPY bil-admin ./bil-admin');
  lines.push('COPY bil-auth ./bil-auth');
  lines.push('COPY bil-comment ./bil-comment');
  lines.push('COPY bil-gateway ./bil-gateway');
  lines.push('COPY bil-interaction ./bil-interaction');
  lines.push('COPY bil-user ./bil-user');
  lines.push('COPY bil-video ./bil-video');
  lines.push('');
  lines.push('RUN mvn -pl ' + name + ' -am clean package -DskipTests');
  lines.push('');
  lines.push('FROM eclipse-temurin:21-jre');
  lines.push('WORKDIR /app');
  lines.push('COPY --from=builder /build/' + name + '/target/' + name + '-1.0.jar app.jar');
  lines.push('EXPOSE ' + port);
  lines.push('ENTRYPOINT ["java", "-Xmx512m", "-jar", "app.jar"]');
  fs.writeFileSync(dir + '/Dockerfile.' + name, lines.join('\n') + '\n', 'utf8');
  console.log('Updated Dockerfile.' + name);
});